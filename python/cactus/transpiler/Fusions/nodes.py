def _attr(
    name: str,
    value: object = None,
    *,
    required: bool = True,
) -> M.AttrConstraint:
    return M.AttrConstraint(name=name, value=value, required=required)


def _node(
    name: str,
    op_key: str,
    *,
    attrs: tuple[M.AttrConstraint, ...] = (),
    repeated: bool = False,
    repeated_group: str | None = None,
    allowed_value_kinds: tuple[str, ...] = (),
    tensor_constraints: tuple[M.TensorConstraint, ...] = (),
    metadata: dict | None = None,
) -> M.FusionNode:
    return M.FusionNode(
        name=name,
        ops=ATEN_OPS[op_key],
        attrs=attrs,
        repeated=repeated,
        repeated_group=repeated_group,
        allowed_value_kinds=allowed_value_kinds,
        tensor_constraints=tensor_constraints,
        metadata=metadata or {},
    )


def _expert_node(name: str, op_key: str) -> M.FusionNode:
    return _node(name, op_key, repeated=True, repeated_group=EXPERT_GROUP)


